"""
The adiabatic rule: a pair quenches if triplet energy transfer is downhill.

Reads   ../dataset/pairs.csv (through pairs.py)
Writes  nothing -- run_benchmark.py collects the predictions

    uv run benchmark/adiabatic.py       score this one theory on its own

WHAT IT PREDICTS

        quenches  <=>  dG_EnT < 0        i.e.  E_T(quencher) < E_T(photocatalyst)

    Nothing else. No threshold, no scale factor, no fitted constant. This is the
    baseline everything else in the folder is measured against, and the whole point of
    it is that it has nothing to tune: whatever Marcus and Rehm-Weller gain, they gain
    over a rule that could not have been fitted to the data.

WHY THE THRESHOLD IS NOT SWEPT, THOUGH IT COULD BE
    The dataset optimum is not at zero. The original implementation found around
    dG < -3 kcal/mol, worth roughly +5 MCC, and attributed the offset to a systematic
    bias in the DFT triplet energies. An earlier round of the same work had swept it to
    -5 kcal/mol and reported a +17 MCC gain, which turned out to be an artifact: the
    labels at the time were themselves generated by a dG_EnT < -5 feasibility rule, so
    the classifier was being fitted to the label-construction rule. That path is not
    ported. It is the clearest case in this project of a large apparent improvement that
    was leakage.

    Sweeping it now would not be leakage -- the labels are measured rate constants -- but
    it would change the question. "Is transfer downhill" is a statement of
    thermodynamics; "is transfer downhill by more than 3 kcal/mol" is a one-parameter
    model calibrated against this screen. Both are defensible, and only the first is a
    baseline, so the first is what runs here.

    The margin the barrier theories show over this rule is therefore a margin over an
    intentionally untuned baseline, and every place that margin is quoted has to say so.
    `run_benchmark.py` reports the free-parameter count next to every score for exactly
    this reason.
"""

import numpy as np
import pandas as pd

import pairs
from theory import Config

NAME = "adiabatic"
DESCRIPTION = "dG_EnT < 0, the zero-parameter thermodynamic rule"


def required_columns():
    return [pairs.DG_ENT]


def prepare(df: pd.DataFrame, **_kwargs):
    pairs.require(df, required_columns(), "the adiabatic rule")
    dG = df[pairs.DG_ENT].to_numpy(dtype=float)
    return {"dG": dG}


def grid():
    return [Config(family="adiabatic", name="adiabatic", n_free=0, params={})]


def classify(prep, cfg: Config) -> np.ndarray:
    with np.errstate(invalid="ignore"):
        return prep["dG"] < 0


def rate_grid():
    """The adiabatic rule states no rate constant, only a sign."""
    return []


def predicted_rate(prep, cfg: Config):
    return None


if __name__ == "__main__":
    import sys

    import run_benchmark

    # Extra flags pass straight through, so `--exclude-pc PC19` and the rest work here
    # exactly as they do on the harness.
    run_benchmark.main(["--theories", NAME, *sys.argv[1:]])
